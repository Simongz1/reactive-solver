#!/usr/bin/env python3
"""Generate an input-only MOOSE transcription of kinetics1D.C's nodal ODEs."""
import argparse
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def constants():
    text = (ROOT / 'include/modelParams.h').read_text()
    keys = ('R', 'cv', 'k', 'rho', 'E1', 'E2', 'Z1', 'Z2', 'a1', 'b1', 'a2', 'b2',
            'Y1_init', 'Y2_init')
    values = {}
    for key in keys:
        match = re.search(r'const double ' + key + r'\s*=\s*([^;]+);', text)
        values[key] = float(match.group(1))
    values['alpha'] = values['k'] / values['rho'] / values['cv']
    return values


def equations(n, length):
    """Return variable -> (LHS source expression, coupled scalar variables)."""
    dx = length / (n - 1)
    result = {}
    for i in range(n):
        y1, y2, y3, t = (f'{name}_{i}' for name in ('Y1', 'Y2', 'Y3', 'T'))
        r1 = f'Z1*exp(-E1/(R*{t}))'
        r2 = f'Z2*exp(-E2/(R*{t}))'
        q1 = f'if({t}>1736.6,a1+b1*({t}-1736.6),a1)'
        q2 = f'if({t}>1736.6,a2+b2*({t}-1736.6),a2)'
        result[y1] = (f'{r1}*{y1}', [t])
        result[y2] = (f'-({r1}*{y1})+{r2}*{y2}', [y1, t])
        result[y3] = (f'-({r2}*{y2})', [y2, t])
        coefficient = f'(alpha/{dx:.17g}/{dx:.17g})'
        if i in (0, n - 1):
            j, k = (1, 2) if i == 0 else (n - 2, n - 3)
            # Deliberately no reaction heating: source C++ overwrites it here.
            rhs = f'0.5*{coefficient}*(-7*{t}+8*T_{j}-T_{k})'
            coupled = [f'T_{j}', f'T_{k}']
        else:
            rhs = (f'({q1}*{r1}*{y1}+{q2}*{r2}*{y2})/cv'
                   f'+{coefficient}*(T_{i+1}-2*{t}+T_{i-1})')
            coupled = [y1, y2, f'T_{i-1}', f'T_{i+1}']
        result[t] = (f'-({rhs})', coupled)
    return result


def initial_values(n, length, hot, cold, width, c):
    result = {}
    for i in range(n):
        is_hot = i * length / (n - 1) < width if width > 0 else 2*n//5 <= i < 3*n//5
        for name, value in [('Y1', c['Y1_init']), ('Y2', c['Y2_init']),
                            ('Y3', 1-c['Y1_init']-c['Y2_init']), ('T', hot if is_hot else cold)]:
            result[f'{name}_{i}'] = value
    return result


def render(n=101, length=250., hot=1920., cold=300., dt=1e-5,
           steps=100000, stride=250, width=20.):
    if n < 3 or length <= 0 or dt <= 0 or cold <= 0 or hot < cold or steps < 0 or stride < 1:
        raise ValueError('Invalid mesh, temperature, time, or output parameters')
    if width < 0 or width >= length or not all(map(math.isfinite, (length, hot, cold, dt, width))):
        raise ValueError('Require finite parameters and 0 <= width < length (zero = centered)')
    c = constants()
    initial = initial_values(n, length, hot, cold, width, c)
    lines = [
        '# Generated by moose/generate_kinetics1d.py; see moose/README.md.',
        '# Exact finite-difference nodal ODE transcription, not a Galerkin FE approximation.',
        f'# N={n}, L={length:g} nm, dx={length/(n-1):.17g} nm, left_hot_width={width:g} nm.',
        '# Endpoints retain the source stencil and omit reaction heating.',
        '# kinetics1D.C advances numSteps+1 steps; this input does the same.',
        '# Scalar variable suffix i denotes x=i*L/(N-1). Mesh below is bookkeeping only.',
        '', '[Mesh]', '  type = GeneratedMesh', '  dim = 1', '  nx = 1', '[]', '', '[Variables]']
    for name, value in initial.items():
        lines.extend([f'  [{name}]', '    family = SCALAR', '    order = FIRST',
                      f'    initial_condition = {value:.17g}', '  []'])
    lines.extend(['[]', '', '[ScalarKernels]'])
    for name, (expression, coupled) in equations(n, length).items():
        used = [key for key in c if re.search(r'\b' + key + r'\b', expression)]
        lines.extend([f'  [time_{name}]', '    type = ODETimeDerivative', f'    variable = {name}', '  []',
                      f'  [residual_{name}]', '    type = ParsedODEKernel', f'    variable = {name}',
                      f"    expression = '{expression}'", f"    coupled_variables = '{' '.join(coupled)}'",
                      f"    constant_names = '{' '.join(used)}'",
                      f"    constant_expressions = '{' '.join(format(c[key], '.17g') for key in used)}'",
                      '    enable_jit = false', '  []'])
    lines.extend(['[]', '', '[Executioner]', '  type = Transient', f'  dt = {dt:.17g}',
                  f'  dtmin = {dt:.17g}', f'  num_steps = {steps+1}', '  abort_on_solve_fail = true',
                  '  [TimeIntegrator]', '    type = ExplicitSSPRungeKutta', '    order = 3',
                  '    solve_type = lumped', '  []', '[]', '', '[Outputs]',
                  '  file_base = kinetics1D_moose', '  [table]', '    type = CSV',
                  "    execute_on = 'INITIAL TIMESTEP_END FINAL'", f'    time_step_interval = {stride}',
                  '  []', '[]', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--nodes', type=int, default=101)
    p.add_argument('--length', type=float, default=250)
    p.add_argument('--hot', type=float, default=1920)
    p.add_argument('--cold', type=float, default=300)
    p.add_argument('--dt', type=float, default=1e-5)
    p.add_argument('--steps', type=int, default=100000, help='C++ numSteps (one extra step is preserved)')
    p.add_argument('--stride', type=int, default=250)
    p.add_argument('--left-hot-width', type=float, default=20, help='nm; 0 selects original centered IC')
    p.add_argument('--output', type=Path, default=Path(__file__).with_name('kinetics1D.i'))
    a = p.parse_args()
    a.output.write_text(render(a.nodes, a.length, a.hot, a.cold, a.dt, a.steps, a.stride, a.left_hot_width))
    print(a.output)
